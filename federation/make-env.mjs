#!/usr/bin/env node
/**
 * Writes the two nodes' environment files and seed rosters for
 * docker-compose.federation.yml. Run after `npm run build`, since it uses the
 * SDK's own key generation and minting rather than a second copy of either.
 *
 *   node federation/make-env.mjs
 *
 * Each node gets a fresh Ed25519 key, accepts one bearer token, and is told the
 * other node's actor URL, public key and the token that node accepts: the
 * prearranged grant of section 2.1, written down once per peer. Node B's seed
 * roster carries a licensee already bound to a ULI minted under B's key, so the
 * adopt flow of section 2.12.2 can run against it.
 *
 * Demo keys and demo tokens: they are generated for this stand-up and are not
 * credentials for anything else.
 */

import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { uoiUrn } from '../dist/node/governance.js';
import { generateKeyPair, mintUli } from '../dist/sdk/uli.js';

const here = dirname(fileURLToPath(import.meta.url));
const PREFIX = '/uli-service/v1';

const nodes = {
  a: { uoi: 'M00000001', host: 'node-a', token: 'tok-node-a' },
  b: { uoi: 'M00000002', host: 'node-b', token: 'tok-node-b' },
};

const keys = Object.fromEntries(Object.entries(nodes).map(([k, n]) => [k, { ...generateKeyPair(), uoi: n.uoi }]));

const entry = (k) => ({
  uoi: nodes[k].uoi,
  uoiUrn: uoiUrn(nodes[k].uoi),
  actor: `http://${nodes[k].host}:3000${PREFIX}/actors/${nodes[k].uoi}`,
  publicKeys: [keys[k].publicKey],
  status: 'active',
  certified: true,
});

const envFor = (self, peer) =>
  [
    `# ${nodes[self].host}: acts for ${nodes[self].uoi}; federates with ${nodes[peer].host} (${nodes[peer].uoi}). Generated by federation/make-env.mjs.`,
    `ULI_NODE_UOI=${nodes[self].uoi}`,
    `ULI_NODE_TENANTS=${nodes[self].uoi}`,
    `ULI_ORIGIN=http://${nodes[self].host}:3000`,
    `ULI_NODE_TOKENS=${nodes[self].token}`,
    `ULI_SIGNING_KEYS=${JSON.stringify({ [nodes[self].uoi]: keys[self].privateKeyPem })}`,
    `ULI_RESOLVERS=${JSON.stringify([entry(peer)])}`,
    `ULI_PEER_TOKENS=${JSON.stringify({ [nodes[peer].uoi]: nodes[peer].token })}`,
    '',
  ].join('\n');

/** Section 2.12.1's Jane, as Provider 1 holds her, and John Smith from the pilot seed. */
const seedA = [
  { MemberFullName: 'Jane A Smith', MemberFirstName: 'Jane', MemberMiddleName: 'A', MemberLastName: 'Smith', MemberNickname: 'Janie', MemberType: 'REALTOR Salesperson', MemberNationalAssociationId: '999000111', MemberStateLicense: 'SL123456', MemberStateLicenseType: 'Salesperson', MemberStateLicenseState: 'CA', MemberMlsId: 'A0001', OfficeName: 'Smith Realty Group', OfficeMlsId: 'OFF001', SourceSystemID: 'M00000001', SourceSystemName: 'Node A MLS', OriginatingSystemID: 'M00000001', OriginatingSystemName: 'Node A MLS' },
  { MemberNationalAssociationId: '012345687', MemberFullName: 'John Smith', MemberFirstName: 'John', MemberLastName: 'Smith', MemberStateLicense: 'RE-884120', MemberStateLicenseState: 'IN', MemberStateLicenseType: 'Salesperson', MemberMlsId: 'A1001', OfficeName: 'Prairie Realty', OfficeMlsId: 'OFC-77', MemberType: 'Agent' },
];

/** Section 2.12.2's Jane as Provider 8 holds her, already bound to a ULI minted under node B's key, plus someone unrelated. */
const janeUli = mintUli({ uoi: uoiUrn(nodes.b.uoi), privateKeyPem: keys.b.privateKeyPem });
const seedB = [
  { UniqueLicenseeIdentifier: janeUli, MemberFullName: 'Jane Smith', MemberFirstName: 'Jane', MemberMiddleName: 'A', MemberLastName: 'Smith', MemberNickname: 'Janie', MemberType: 'REALTOR Salesperson', MemberNationalAssociationId: '999000111', MemberStateLicense: 'SL123456', MemberStateLicenseType: 'Salesperson', MemberStateLicenseState: 'CA', MemberMlsId: 'B7788', OfficeName: 'Smith Realty Group', OfficeMlsId: 'OFF042', SourceSystemID: 'M00000002', SourceSystemName: 'Node B MLS', OriginatingSystemID: 'M00000002', OriginatingSystemName: 'Node B MLS' },
  { MemberFullName: 'Ada Lovelace', MemberFirstName: 'Ada', MemberLastName: 'Lovelace', MemberStateLicense: 'L1', MemberStateLicenseState: 'IN', MemberMlsId: 'B0002', OfficeName: 'Analytical Realty', OfficeMlsId: 'OFC-01', MemberType: 'Agent' },
];

mkdirSync(here, { recursive: true });
writeFileSync(join(here, 'node-a.env'), envFor('a', 'b'));
writeFileSync(join(here, 'node-b.env'), envFor('b', 'a'));
writeFileSync(join(here, 'seed-a.json'), `${JSON.stringify(seedA, null, 2)}\n`);
writeFileSync(join(here, 'seed-b.json'), `${JSON.stringify(seedB, null, 2)}\n`);
writeFileSync(join(here, 'keys.json'), `${JSON.stringify({ a: { uoi: nodes.a.uoi, publicKey: keys.a.publicKey }, b: { uoi: nodes.b.uoi, publicKey: keys.b.publicKey }, janeUli }, null, 2)}\n`);

console.log(`node-a ${nodes.a.uoi} key ${keys.a.publicKey}`);
console.log(`node-b ${nodes.b.uoi} key ${keys.b.publicKey}`);
console.log(`node-b holds Jane under ${janeUli}`);
console.log('wrote federation/node-a.env node-b.env seed-a.json seed-b.json keys.json');
